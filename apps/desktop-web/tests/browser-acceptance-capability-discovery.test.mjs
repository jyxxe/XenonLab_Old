import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {existsSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createServer} from 'vite';
import {chromium,expect} from '@playwright/test';
const appRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
test('unified discovery drives native apps and removes disabled plugin windows/widgets',async t=>{
  const executablePath=process.env.CHROME_BIN||chromium.executablePath();
  if(!existsSync(executablePath))return t.skip('Chrome unavailable');
  const server=await createServer({root:appRoot,server:{host:'127.0.0.1',port:0,watch:null}});
  let browser;
  try{
    await server.listen();
    browser=await chromium.launch({headless:true,executablePath,args:['--no-sandbox','--disable-dev-shm-usage']});
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',error=>errors.push(String(error)));
    await page.route('https://discovery.example/**',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><p>Synthetic isolated plugin</p>'}));
    const base=`http://127.0.0.1:${server.httpServer.address().port}`;
    await page.goto(base+'/tests/shell-fixture.html?scenario=capability-discovery');
    await expect(page.locator('nav.dock button[title="知识库"]')).toBeVisible();
    await expect(page.locator('.widgets iframe')).toHaveCount(1);
    await page.locator('button[title="LaunchPad"]').click();
    await page.locator('.launchpad-search').fill('Discovery app');
    await page.locator('.launchpad-app').click();
    const plugin=page.locator('.window[data-app-id="discovery-app"]');
    await expect(plugin).toBeVisible();
    assert.equal(await plugin.locator('iframe').getAttribute('sandbox'),'allow-same-origin allow-scripts allow-forms');
    await page.locator('nav.dock button[title="系统设置"]').click();
    await page.locator('.settings-tabs button').filter({hasText:'插件'}).click();
    await page.locator('.plugin-card label').filter({hasText:'启用'}).locator('input').uncheck();
    await expect(plugin).toHaveCount(0);
    await expect(page.locator('.widgets iframe')).toHaveCount(0);
    assert.equal(await page.evaluate(()=>window.shellFixture.registry.some(item=>item.id==='discovery-app')),true,'stale descriptor still exists');
    await page.locator('button[title="LaunchPad"]').click();
    await page.locator('.launchpad-search').fill('Discovery app');
    await expect(page.locator('.launchpad-app')).toHaveCount(0);
    await page.keyboard.press('Escape');
    await page.locator('.plugin-card label').filter({hasText:'启用'}).locator('input').check();
    await expect(page.locator('.widgets iframe')).toHaveCount(1);
    await page.locator('button[title="LaunchPad"]').click();
    await page.locator('.launchpad-search').fill('Discovery app');
    await expect(page.locator('.launchpad-app')).toHaveCount(1);
    await page.keyboard.press('Escape');
    const evidence=path.resolve(appRoot,'../../runtime/verification/issue305-discovery');
    await fs.mkdir(evidence,{recursive:true});
    await page.screenshot({path:path.join(evidence,'desktop.png')});
    await page.goto(base+'/tests/shell-fixture.html?scenario=capability-error');
    await expect(page.getByText('Synthetic capability discovery unavailable',{exact:false})).toBeVisible();
    await expect(page.locator('nav.dock')).toHaveCount(0);
    assert.deepEqual(errors,[]);
  }finally{await browser?.close();await server.close()}
});
